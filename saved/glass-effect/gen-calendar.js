// node gen-calendar.js /path/to/uk-airshow-calendar.html > content-calendar.js
const fs = require('fs');
const t = fs.readFileSync(process.argv[2], 'utf8');
const D = JSON.parse(t.match(/var D=(\[\[.*?\]\]);/s)[1]), T = JSON.parse(t.match(/var T=(\[\[.*?\]\]);/s)[1]);
const M = ['May', 'June', 'July', 'August', 'September', 'October'];
const MS = { Jan: 'January', Feb: 'February', Mar: 'March', Apr: 'April', May: 'May', Jun: 'June', Jul: 'July', Aug: 'August', Sep: 'September', Oct: 'October' };
const BG = ['dx-formation', 'cosredloop', 'typhoon', 'eastbourne', 'bp-wing', 'sw-speedsix'];
const q = s => JSON.stringify(s);
const chunk = (a, n) => { const o = []; for (let i = 0; i < a.length; i += n) o.push(a.slice(i, i + n)); if (o.length > 1 && o[o.length - 1].length === 1) o[o.length - 2].push(...o.pop()); return o; };
const dateOf = (d, m) => /[A-Za-z]/.test(d[4].replace(/ to /g, '')) ? d[4].replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct)\b/g, x => MS[x]) : d[4] + ' ' + m;
const stops = [];
M.forEach((m, mi) => {
  const rows = D.filter(d => d[0] === mi); if (!rows.length) return;
  const pts = chunk(rows, 3).map(g => `      { o: { uniform: true, gap: 12 }, bg: { img: 'p:${BG[mi]}', imgL: 'p:${BG[mi]}', bright: .26 }, lines: [${g.map(d => `['mid', ${q(dateOf(d, m))}], ['small', ${q(d[6])}, { col: '#fff' }], ['small', ${q(d[8])}]`).join(', ')}] }`);
  stops.push(`    ['${m}', '${rows.length} ${rows.length === 1 ? 'show' : 'shows'}', [\n${pts.join(',\n')},\n    ]]`);
});
const tp = chunk(T, 4).map(g => `      { o: { uniform: true, gap: 12 }, lines: [['mid', 'Date to be confirmed'], ${g.map(x => `['small', ${q(x[0])}, { col: '#fff' }], ['small', ${q(x[2])}]`).join(', ')}] }`);
stops.push(`    ['Date to be|confirmed', '${T.length} shows', [\n${tp.join(',\n')},\n    ]]`);
console.log(`// The full UK air show calendar 2027, generated by gen-calendar.js from uk-airshow-calendar.html (dates correct as of 10 October 2026).
// ${D.length} shows with 2027 dates month by month, then ${T.length} shows whose dates are still to be confirmed (no date shown for those).
window.FILM = {
  url: 'ukairshowguide.co.uk', readLine: 'See the full calendar, with filters, at', stepLabel: false, pointBeats: 9,
  introBeats: 12,
  intro: [
    [0, 4, [['big', 'The UK'], ['huge', 'air show'], ['big', 'calendar 2027']], { stagger: B / 2, exit: 'zoom' }],
    [4, 8.5, [['huge', '[${D.length + T.length}|p:redarrows]', { size: 380, enter: 'slam' }], ['big', 'shows in one place', { enter: 'slam', delay: B / 2 }], ['small', '${D.length} with dates, ${T.length} still to be confirmed']], { stagger: B, exit: 'zoom', boom: true }],
    [8.5, 12, [['small', 'Month by month'], ['huge', '*May to Oct*', { enter: 'pop' }], ['mid', 'then the dates still to come']], { stagger: B / 2, exit: 'left' }],
  ],
  stops: [
${stops.join(',\n')},
  ],
  outro: [['big', 'Plan your'], ['huge', '[2027|p:typhoon]', { size: 380, enter: 'slam' }], ['big', 'season']],
};`);
