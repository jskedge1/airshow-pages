// Writes data.gen.js for the train map film from the site's own train data, so the film never
// invents a station, line or change:  node cartoons/_rail/map/gen-data.mjs
//   journey-planner.js  STA (station coordinates), LINES (who runs what, calling where), SHOWS (the last leg)
//   london-links.js     the Tube links from London Victoria (line and minutes)
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.resolve(here, '../../..');
const win = {};
const doc = { addEventListener() {}, readyState: 'loading', querySelectorAll: () => [], getElementById: () => null };
vm.runInNewContext(fs.readFileSync(path.join(root, 'journey-planner.js'), 'utf8'), { window: win, document: doc });
const J = win.UKAG_JP;
const r3 = (x) => Math.round(x * 10000) / 10000;
const STA = {};
for (const [c, [name, lat, lon]] of Object.entries(J.STA)) STA[c] = [name, r3(lon), r3(lat)];
const LINES = J.LINES.map(([op, name, st]) => [op, name, st.map((s) => s[0])]);
const SHOWS = {};
for (const [k, s] of Object.entries(J.SHOWS)) SHOWS[k] = { name: s.name, at: [r3(s.dest[1]), r3(s.dest[0])], arr: s.arr.map((a) => ({ c: a.c, how: a.how, m: a.m })) };
const src = fs.readFileSync(path.join(root, 'london-links.js'), 'utf8');
const LINKS = JSON.parse(src.match(/var LINKS = (\{.*?\});/s)[1]);
const VIC = {};
for (const [k, steps] of Object.entries(LINKS)) {
  const [a, b] = k.split('|'); if (a !== 'London Victoria' || !b.startsWith('London')) continue;
  VIC[b] = steps.map((s) => (s.w ? { walk: s.w, m: s.m } : { lines: s.l, from: s.fn, to: s.tn, m: s.m }));
}
// every cross-London link between two main stations, as london-links.js gives it, and the planner's short walks
const CRS = {}; for (const [c, v] of Object.entries(J.STA)) CRS[v[0]] = c;
const TUBE = {};
for (const [k, steps] of Object.entries(LINKS)) {
  const [a, b] = k.split('|'); if (!CRS[a] || !CRS[b] || !a.startsWith('London') || !b.startsWith('London')) continue;
  TUBE[CRS[a] + '-' + CRS[b]] = steps.map((s) => (s.w ? { walk: s.w, m: s.m } : { lines: s.l, from: s.fn, to: s.tn, m: s.m, br: s.br }));
}
const WALKS = J.LINES.filter((l) => l[0] === 'Walk').map((l) => ({ a: l[2][0][0], b: l[2][1][0], m: l[2][1][1] }));
const out = `// Generated by _rail/map/gen-data.mjs from journey-planner.js and london-links.js. Do not edit.
const DATA = {
  STA: ${JSON.stringify(STA)},
  LINES: ${JSON.stringify(LINES)},
  SHOWS: ${JSON.stringify(SHOWS)},
  VIC: ${JSON.stringify(VIC)},
  TUBE: ${JSON.stringify(TUBE)},
  WALKS: ${JSON.stringify(WALKS)},
};
`;
fs.writeFileSync(path.join(here, 'data.gen.js'), out);
console.log('wrote data.gen.js', Object.keys(STA).length, 'stations', LINES.length, 'lines', Object.keys(SHOWS).length, 'shows');
