// Writes coast.gen.js: the coastline for the train map film, from Natural Earth (public domain) 1:10m countries.
// Needs the npm packages world-atlas@2 and topojson-client@3 (not committed):
//   mkdir /tmp/ne && cd /tmp/ne && npm init -y && npm i world-atlas@2 topojson-client@3
//   NODE_PATH=/tmp/ne/node_modules node cartoons/_rail/map/gen-coast.mjs
import { createRequire } from 'node:module'; import fs from 'node:fs'; import path from 'node:path';
const require = createRequire(import.meta.url);
const t = require('topojson-client'), w = require('world-atlas/countries-10m.json');
const here = path.dirname(new URL(import.meta.url).pathname);
const KX = Math.cos(52.5 * Math.PI / 180);
// Douglas-Peucker, tolerance in degrees of latitude
function simplify(r, tol) {
  const keep = new Uint8Array(r.length); keep[0] = keep[r.length - 1] = 1; const st = [[0, r.length - 1]];
  while (st.length) { const [a, b] = st.pop(); let md = 0, mi = -1; const ax = r[a][0] * KX, ay = r[a][1], bx = r[b][0] * KX, by = r[b][1], dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) { const d = L < 1e-6 ? Math.hypot(r[i][0] * KX - ax, r[i][1] - ay) : Math.abs((r[i][0] * KX - ax) * dy - (r[i][1] - ay) * dx) / L; if (d > md) { md = d; mi = i; } }
    if (md > tol) { keep[mi] = 1; st.push([a, mi], [mi, b]); } }
  return r.filter((_, i) => keep[i]);
}
const span = (r) => { const xs = r.map((q) => q[0] * KX), ys = r.map((q) => q[1]); return Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)); };
const rings = (name, tol, minSpan) => {
  const f = t.feature(w, w.objects.countries).features.find((x) => x.properties.name === name);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  return polys.map((p) => p[0]).filter((r) => { const xs = r.map((q) => q[0]), ys = r.map((q) => q[1]); return Math.max(...xs) > -11.5 && Math.min(...xs) < 5 && Math.max(...ys) > 48.6 && Math.min(...ys) < 61; })
    .filter((r) => span(r) > minSpan).map((r) => simplify(r, tol).filter((q) => q[1] > 47.5 && q[0] < 7).map(([x, y]) => [Math.round(x * 1000) / 1000, Math.round(y * 1000) / 1000]));
};
const uk = rings('United Kingdom', 0.004, 0.06), im = rings('Isle of Man', 0.004, 0.05);
const far = [...rings('Ireland', 0.012, 0.1), ...rings('France', 0.012, 0.1), ...rings('Belgium', 0.02, 0.1), ...rings('Netherlands', 0.02, 0.1)];
fs.writeFileSync(path.join(here, 'coast.gen.js'), `// Generated by _rail/map/gen-coast.mjs from Natural Earth 1:10m (public domain). Do not edit.
const COAST = {
  uk: ${JSON.stringify([...uk, ...im])},
  far: ${JSON.stringify(far)},
};
`);
console.log('uk rings', uk.length, 'points', uk.reduce((s, r) => s + r.length, 0), '| far rings', far.length, 'points', far.reduce((s, r) => s + r.length, 0));
